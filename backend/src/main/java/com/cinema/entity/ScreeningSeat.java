package com.cinema.entity;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import java.time.Instant;

/**
 * One physical seat for ONE screening (e.g. seat B7 of screening #3).
 *
 * *** OPTIMISTIC LOCKING ***
 * The @Version column is the heart of the concurrency solution. Hibernate adds it to every UPDATE:
 *     UPDATE screening_seat SET status=?, version=version+1 WHERE id=? AND version=?
 * If two users loaded the same seat at version 0 and both try to hold it, the first UPDATE
 * succeeds (version becomes 1). The second UPDATE matches 0 rows, so Hibernate throws
 * ObjectOptimisticLockingFailureException, which GlobalExceptionHandler turns into HTTP 409.
 * No database row locks are held while users are thinking, so it scales well.
 */
@Entity
@Getter @Setter
@Table(uniqueConstraints = @UniqueConstraint(columnNames = {"screening_id", "rowLabel", "seatNumber"}))
public class ScreeningSeat {
    @Id @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Version
    private Long version;

    @ManyToOne(optional = false, fetch = FetchType.LAZY)
    private Screening screening;

    private String rowLabel;   // "A", "B", ...
    private int seatNumber;    // 1, 2, 3, ...

    @Enumerated(EnumType.STRING)
    private SeatStatus status = SeatStatus.AVAILABLE;

    /** Random id generated by the browser; identifies WHO holds the seat (no login needed). */
    private String holdToken;
    private Instant heldUntil;

    /** Set once the seat is paid for. */
    @ManyToOne(fetch = FetchType.LAZY)
    private Booking booking;

    // ---- small helper methods so the service code reads like English ----

    /** Free = never held, or held but the 10-minute timer already ran out. */
    public boolean isFree(Instant now) {
        return status == SeatStatus.AVAILABLE
                || (status == SeatStatus.HELD && heldUntil != null && heldUntil.isBefore(now));
    }

    public void hold(String token, Instant until) {
        this.status = SeatStatus.HELD;
        this.holdToken = token;
        this.heldUntil = until;
    }

    public void release() {
        this.status = SeatStatus.AVAILABLE;
        this.holdToken = null;
        this.heldUntil = null;
    }

    public void book(Booking booking) {
        this.status = SeatStatus.BOOKED;
        this.booking = booking;
        this.holdToken = null;
        this.heldUntil = null;
    }

    public String label() { return rowLabel + seatNumber; }
}
